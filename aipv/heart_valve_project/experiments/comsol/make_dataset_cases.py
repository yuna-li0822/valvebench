"""Design table for the COMSOL training dataset (the axisymmetric ring model in the
shape-memory regime, suture stiffness 1000x realistic).

Mirrors the synthetic PINNVALVE setup (valvebench/datasets/synthetic.py): designs for
train/val/test are Latin-hypercube samples of an interior sub-box, and the 16 corners of
the full box are the out-of-distribution test set.

Design variables. Suture count and suture stiffness both only scale the total suture
stiffness K0 in this model, so varying both would make them indistinguishable; suture
stiffness is fixed and crimp depth is varied instead.

    Suture_Count      4 - 11        number of sutures (continuous, as in the synthetic generator)
    Dissolution_Rate  0.05 - 0.3    suture stiffness decay rate, 1/month
    Crimp_mm          0.3 - 0.7     radial crimp of the outer surface (diameter 26 -> 25.4 .. 24.6 mm)
    Af_C              20 - 30       austenite finish temperature, deg C (body temperature is 37)

Writes experiments/comsol/cases_dataset.txt (for run_ring_sweep.py) and
data/comsol/comsol_dataset_designs.csv.

Usage:
    py -3 aipv/heart_valve_project/experiments/comsol/make_dataset_cases.py
"""
from itertools import product
from pathlib import Path

import pandas as pd
from scipy.stats import qmc

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]

FULL = {"Suture_Count": (4, 11), "Dissolution_Rate": (0.05, 0.3), "Crimp_mm": (0.3, 0.7), "Af_C": (20.0, 30.0)}
INTERIOR = {"Suture_Count": (5, 9), "Dissolution_Rate": (0.08, 0.25), "Crimp_mm": (0.38, 0.62), "Af_C": (22.0, 28.0)}
N_INTERIOR = 120
SEED = 7
K_SCALE = 1000
MESH = "8,20"


def design_table():
    names = list(FULL)
    lo = [INTERIOR[n][0] for n in names]
    hi = [INTERIOR[n][1] for n in names]
    pts = qmc.scale(qmc.LatinHypercube(d=len(names), seed=SEED).random(N_INTERIOR), lo, hi)
    rows = [dict(zip(names, p), set="interior") for p in pts]
    for corner in product(*[FULL[n] for n in names]):
        rows.append(dict(zip(names, corner), set="ood_corner"))
    df = pd.DataFrame(rows)
    df.insert(0, "design_id", [f"ds{i:03d}" for i in range(len(df))])
    return df.round({"Suture_Count": 4, "Dissolution_Rate": 5, "Crimp_mm": 5, "Af_C": 4})


def case_line(r):
    overrides = f"TAf={r.Af_C + 273.15:.4f}[K]|P_U0={r.Crimp_mm}[mm]"
    return f"{r.design_id};{MESH};{K_SCALE};{r.Suture_Count};{r.Dissolution_Rate};{overrides}"


def main():
    df = design_table()
    df.to_csv(PROJECT / "data" / "comsol" / "comsol_dataset_designs.csv", index=False)
    lines = ["# COMSOL training dataset, generated by make_dataset_cases.py; see run_ring_sweep.py for the format"]
    lines += [case_line(r) for r in df.itertuples()]
    (HERE / "cases_dataset.txt").write_text("\n".join(lines) + "\n")
    print(df.groupby("set").size().to_string())
    print(df.describe().round(3).to_string())


if __name__ == "__main__":
    main()

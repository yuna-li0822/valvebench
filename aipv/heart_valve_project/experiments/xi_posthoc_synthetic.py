"""Fair baseline for PINNVALVE's martensite (xi) recovery on synthetic data.

The data-only network (physics_weight 0) never receives a gradient on its xi head, so
comparing PINNVALVE's xi against that head compares a trained output with an untrained one.
The fair baseline takes the data-only network's predicted diameter and computes xi from it
after training, with the same equations the physics loss uses
(valvebench.models.pinn_scaffold.xi_from_diameter). If that matches PINNVALVE, the xi
result comes from the closure, not from training with physics.

Conditions (main-ablation TrainConfig, nothing re-tuned; OOD = 16 design-box corners at
baseline noise):
  clean    noise_scale 0.1 (the main ablation), 5 seeds
  noise    training noise_scale 0.3 and 1.0, 3 seeds
  sparse   diameter labelled only at t = 0, 6, 12 or t = 0, 12; PINNVALVE enforces physics
           at all 5 timepoints (collocation), 3 seeds

Usage:
    py -3 aipv/heart_valve_project/experiments/xi_posthoc_synthetic.py
"""
import json
import sys
from pathlib import Path

import numpy as np

try:
    import torch  # noqa: F401
except Exception:
    print('torch not installed - skipped. pip install -e "aipv/heart_valve_project[pinn]"')
    raise SystemExit(0)

_PROJECT_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_PROJECT_DIR))

from valvebench.datasets.synthetic import interior_train_val_test_split_sma, ood_corner_dataset_sma  # noqa: E402
from valvebench.models.pinn_scaffold import (  # noqa: E402
    TrainConfig, predict_latent, train_scaffold_pinn, xi_from_diameter)

OUT_JSON = _PROJECT_DIR / "experiments" / "xi_posthoc_synthetic_results.json"
OUT_MD = _PROJECT_DIR / "experiments" / "xi_posthoc_synthetic_report.md"


def _rmse(a, b):
    return float(np.sqrt(np.mean((np.asarray(a) - np.asarray(b)) ** 2)))


def score(model, df):
    d, _, xi = predict_latent(model, df)
    return {"d_rmse": _rmse(d, df.Diameter_mm), "xi_head": _rmse(xi, df.Xi),
            "xi_posthoc": _rmse(xi_from_diameter(d, df), df.Xi)}


def run(train_df, id_df, ood_df, seeds, collocation_df=None):
    runs = []
    for s in seeds:
        mlp = train_scaffold_pinn(train_df, TrainConfig(physics_weight=0.0, seed=s)).model
        pinn = train_scaffold_pinn(train_df, TrainConfig(seed=s), collocation_df=collocation_df).model
        r = {"mlp": {"id": score(mlp, id_df), "ood": score(mlp, ood_df)},
             "pinn": {"id": score(pinn, id_df), "ood": score(pinn, ood_df)}}
        print(f"  seed {s}  OOD xi: mlp head {r['mlp']['ood']['xi_head']:.3f}  "
              f"mlp+closure {r['mlp']['ood']['xi_posthoc']:.3f}  pinn head {r['pinn']['ood']['xi_head']:.3f}  "
              f"pinn+closure {r['pinn']['ood']['xi_posthoc']:.3f}", flush=True)
        runs.append(r)
    return runs


def _ms(runs, model, split, metric):
    v = np.array([r[model][split][metric] for r in runs])
    return f"{v.mean():.3f} ± {v.std(ddof=1):.3f}"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    train_df, _, id_df = interior_train_val_test_split_sma(n_samples=120, seed=1)
    ood_df = ood_corner_dataset_sma(seed=123)
    true_ceiling = {"id": _rmse(xi_from_diameter(id_df.Diameter_mm.values, id_df), id_df.Xi),
                    "ood": _rmse(xi_from_diameter(ood_df.Diameter_mm.values, ood_df), ood_df.Xi)}

    results = {"closure_on_true_diameter": true_ceiling, "conditions": {}}
    conds = results["conditions"]
    print("clean")
    conds["clean (noise 0.1)"] = run(train_df, id_df, ood_df, (0, 1, 2, 3, 4))
    for noise in (0.3, 1.0):
        print(f"noise {noise}")
        noisy, _, _ = interior_train_val_test_split_sma(n_samples=120, seed=1, noise_scale=noise)
        conds[f"training noise {noise}"] = run(noisy, id_df, ood_df, (0, 1, 2))
    for keep in ((0.0, 6.0, 12.0), (0.0, 12.0)):
        print(f"sparse {keep}")
        conds[f"labels at t = {', '.join(f'{t:g}' for t in keep)}"] = run(
            train_df[train_df.t_months.isin(keep)], id_df, ood_df, (0, 1, 2), collocation_df=train_df)

    OUT_JSON.write_text(json.dumps(results, indent=1), encoding="utf-8")
    L = ["# Post-hoc ξ baseline on synthetic data", "",
         "Auto-generated by `experiments/xi_posthoc_synthetic.py`. ξ (martensite fraction) is never supervised. "
         "\"head\" = the network's own ξ output; \"+ closure\" = ξ computed after training from the network's "
         "predicted diameter with the physics loss's own equations (`pinn_scaffold.xi_from_diameter`). The "
         "data-only network's head is never trained, so \"data-only + closure\" is the fair baseline for PINNVALVE.", "",
         f"Closure applied to the true (noisy) diameters: ID ξ RMSE {true_ceiling['id']:.3f}, "
         f"OOD {true_ceiling['ood']:.3f}.", "",
         "| condition | data-only head | data-only + closure | PINNVALVE head | PINNVALVE + closure | "
         "data-only OOD D RMSE (mm) | PINNVALVE OOD D RMSE (mm) |",
         "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for name, runs in conds.items():
        L.append(f"| {name} | {_ms(runs, 'mlp', 'ood', 'xi_head')} | {_ms(runs, 'mlp', 'ood', 'xi_posthoc')} | "
                 f"{_ms(runs, 'pinn', 'ood', 'xi_head')} | {_ms(runs, 'pinn', 'ood', 'xi_posthoc')} | "
                 f"{_ms(runs, 'mlp', 'ood', 'd_rmse')} | {_ms(runs, 'pinn', 'ood', 'd_rmse')} |")
    L += ["", "All ξ columns are OOD RMSE (16 corners), mean ± SD over seeds (5 clean, 3 otherwise).", ""]
    OUT_MD.write_text("\n".join(L), encoding="utf-8")
    print(f"-> {OUT_JSON}\n-> {OUT_MD}")


if __name__ == "__main__":
    main()

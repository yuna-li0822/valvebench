"""Predicted release time per design: when does a suture break?

Absorbable sutures do not soften gradually; they keep holding until their remaining strength
falls below the load they carry, then break. With the sutures tied one after another around
the middle row (in series), every suture carries the row's full hoop tension, and the first
break releases the whole row. So the release time is the first time at which

    rated strength x retention(t) < load per suture.

Inputs (all stated, none fitted to this project's data):
- Rated strength: USP minimum knot-pull for size 2-0 synthetic absorbable suture, 2.68 kgf
  (26.3 N). A double-stranded suture is taken as 2x that (strands share the load equally).
- Retention: PDS II (Ethicon), 80 / 70 / 60% at 2 / 4 / 6 weeks; complete absorption 182-238 days.
  Retention is measured only to 6 weeks, so two extrapolations bracket the answer:
    exponential  least-squares fit of R = exp(-k t) to the 2/4/6-week points
    linear-zero  linear interpolation of the data, then linear from 60% at 6 weeks to 0 at
                 182 days (the earliest complete-absorption time)
- Load per suture at the held diameter: RESULTS.md section 7d (lattice-cell model with realistic
  sutures, tied in series around the middle row).

Usage:
    py -3 aipv/heart_valve_project/experiments/suture_release_time.py
"""
import math
from pathlib import Path

import numpy as np

OUT_MD = Path(__file__).resolve().parent / "suture_release_time_report.md"

KNOT_PULL_N = 2.68 * 9.80665          # USP minimum, size 2-0 synthetic absorbable
RET_WEEKS = np.array([0.0, 2.0, 4.0, 6.0])
RET_FRAC = np.array([1.0, 0.8, 0.7, 0.6])
ABSORB_WEEKS = (182 / 7, 238 / 7)

DESIGNS = [  # name, sutures, strands per suture, load per suture (N), held diameter (mm)
    ("12 cells, 10 mm struts", 12, 1, 1.1, 13.3),
    ("Taper 0.4 -> 0.15 mm", 12, 1, 9.1, 15.5),
    ("Taper 0.4 -> 0.15 mm", 6, 2, 14.3, 14.0),
]

K_EXP = -np.sum(RET_WEEKS[1:] * np.log(RET_FRAC[1:])) / np.sum(RET_WEEKS[1:] ** 2)  # per week


def t_exponential(r):
    return math.log(1 / r) / K_EXP


def t_linear_zero(r):
    if r >= RET_FRAC[-1]:
        return float(np.interp(-r, -RET_FRAC, RET_WEEKS))
    return RET_WEEKS[-1] + (RET_FRAC[-1] - r) / (RET_FRAC[-1] / (ABSORB_WEEKS[0] - RET_WEEKS[-1]))


def fmt_weeks(w):
    return f"{w:.0f} wk ({w / 4.345:.1f} mo)"


def main():
    rows = []
    for name, n, strands, load, held in DESIGNS:
        strength = strands * KNOT_PULL_N
        r = load / strength
        te, tl = t_exponential(r), t_linear_zero(r)
        note = ""
        if te > ABSORB_WEEKS[0]:
            note = "exponential fit outlasts absorption; release at absorption at the latest"
            te = min(te, ABSORB_WEEKS[1])
        rows.append((name, n, strands, load, held, strength, r, tl, te, note))
    L = ["# Predicted suture release time per design", "",
         "Auto-generated by `experiments/suture_release_time.py` (see its docstring for every input). "
         "A suture holds until rated strength × retention falls below its load, then breaks. In series, "
         "the first break releases the whole row.", "",
         f"Rated strength {KNOT_PULL_N:.1f} N per strand (USP minimum knot-pull, 2-0). PDS II retention "
         f"80/70/60% at 2/4/6 weeks; exponential fit k = {K_EXP:.4f}/week ({K_EXP * 4.345:.2f}/month). "
         f"Complete absorption {ABSORB_WEEKS[0]:.0f}–{ABSORB_WEEKS[1]:.0f} weeks.", "",
         "| design | sutures | strands | load per suture (N) | held at (mm) | strength (N) | load / strength | "
         "release, linear-to-zero | release, exponential |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for name, n, strands, load, held, strength, r, tl, te, note in rows:
        L.append(f"| {name} | {n} | {strands} | {load} | {held} | {strength:.1f} | {r:.3f} | {fmt_weeks(tl)} | "
                 f"{fmt_weeks(te)}{' *' if note else ''} |")
    L += ["", "\\* The exponential fit never reaches zero, so for this low load it outlasts complete absorption; "
          "the suture cannot hold past absorption, so its release is set to the absorption window.", "",
          "**Single-strand check for the double-stranded design:** if one strand carried the full 14.3 N, "
          f"load/strength = {14.3 / KNOT_PULL_N:.2f} and release would come at "
          f"{fmt_weeks(t_linear_zero(14.3 / KNOT_PULL_N))} (linear-to-zero) or "
          f"{fmt_weeks(t_exponential(14.3 / KNOT_PULL_N))} (exponential).", "",
          "**Uncertainty, in both directions.** The USP value is a minimum; real sutures are usually stronger, which "
          "delays release. But in series the row lets go at the *first* break, so strength scatter between "
          "sutures, knot weakening, and in-vivo loading (cyclic, higher than the static crimp load) all bring "
          "release earlier. Retention after 6 weeks is extrapolated.", "",
          "**Compared with growth:** expanding from 13 to 26 mm takes about 15 years of annular growth "
          "(Discussion §4.1). Every design releases within the first year."]
    OUT_MD.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()

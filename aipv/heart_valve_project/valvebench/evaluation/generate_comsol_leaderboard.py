"""Third VALVEBENCH leaderboard: the COMSOL scaffold task.

Task: predict scaffold diameter from design (Suture_Count, Dissolution_Rate, Crimp_mm, Af_C)
and time, on finite-element data (data/comsol/comsol_dataset.csv, valvebench.datasets.comsol).
Unlike scaffold_leaderboard.md, the targets do not come from the equations in any model's
loss, so every row is tested against an independent simulator.

Rows: the generic baselines (fit on design + time), a data-only network with PINNVALVE's
architecture (physics_weight 0), and PINNVALVE with the reduced-order ring physics
(valvebench.models.pinn_comsol). Held-out interior designs (ID) and the 16 design-box
corners (OOD), 5 seeds, mean ± SD. The ξ column scores the never-supervised martensite
output against COMSOL's volume-averaged value; models without a ξ output show "—".
"""
from pathlib import Path

import numpy as np

try:
    from ..datasets.comsol import DATASET_VERSION, DESIGN_COLUMNS, TARGET, comsol_splits, load_comsol_dataset
    from ..models import BaselineLinear, BaselineMLP, GradientBoostingBaseline, RidgeRegression
except ImportError:  # pragma: no cover - direct script execution
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    from valvebench.datasets.comsol import DATASET_VERSION, DESIGN_COLUMNS, TARGET, comsol_splits, load_comsol_dataset
    from valvebench.models import BaselineLinear, BaselineMLP, GradientBoostingBaseline, RidgeRegression

SEEDS = (0, 1, 2, 3, 4)
FEATURES = DESIGN_COLUMNS + ["t_months"]
BASELINES = {
    "linear": lambda s: BaselineLinear(),
    "ridge": lambda s: RidgeRegression(),
    "gbm": lambda s: GradientBoostingBaseline(random_state=s),
    "mlp": lambda s: BaselineMLP(random_state=s),
}


def _metrics(y, p):
    err = np.asarray(p).ravel() - np.asarray(y).ravel()
    return float(np.sqrt(np.mean(err ** 2))), float(np.mean(np.abs(err)))


def run(seeds=SEEDS, epochs=None):
    parts = comsol_splits(load_comsol_dataset())
    train, test, ood = parts["train"], parts["test"], parts["ood"]
    rows = {}
    for name, make in BASELINES.items():
        res = []
        for s in seeds:
            model = make(s).fit(train[FEATURES].values, train[[TARGET]].values)
            res.append(_metrics(test[TARGET], model.predict(test[FEATURES].values))
                       + _metrics(ood[TARGET], model.predict(ood[FEATURES].values)) + (np.nan, np.nan))
        rows[name] = np.array(res)
    try:
        from ..models.pinn_comsol import TrainConfig, predict_latent, train_ring_pinn
    except ImportError:
        from valvebench.models.pinn_comsol import TrainConfig, predict_latent, train_ring_pinn
    for name, w in (("network, physics_weight 0", 0.0), ("PINNVALVE", 1.0)):
        res = []
        for s in seeds:
            cfg = TrainConfig(physics_weight=w, seed=s) if epochs is None else TrainConfig(physics_weight=w, seed=s, epochs=epochs)
            model = train_ring_pinn(train, cfg).model
            d_t, _, xi_t = predict_latent(model, test)
            d_o, _, xi_o = predict_latent(model, ood)
            res.append(_metrics(test[TARGET], d_t) + _metrics(ood[TARGET], d_o)
                       + (float(np.sqrt(np.mean((xi_t - test.Xi_avg) ** 2))), float(np.sqrt(np.mean((xi_o - ood.Xi_avg) ** 2)))))
        rows[name] = np.array(res)
    return rows, {k: v.design_id.nunique() for k, v in parts.items()}


def render(rows, sizes, seeds):
    def ms(col):
        return "—" if np.all(np.isnan(col)) else f"{np.nanmean(col):.4f} ± {np.nanstd(col, ddof=1):.4f}"

    lines = ["# COMSOL Scaffold Leaderboard", "",
             "Task: predict scaffold diameter (mm) from design (suture count, dissolution rate, crimp depth, "
             "austenite finish temperature) and time, on COMSOL finite-element data "
             f"(`data/comsol/comsol_dataset.csv`, dataset {DATASET_VERSION}). Unlike `scaffold_leaderboard.md`, "
             "no model's loss contains the equations that produced the targets.", "",
             f"Designs: {sizes}. Seeds {list(seeds)}, mean ± SD. ID = held-out interior designs; OOD = the 16 "
             "corners of the design box. ξ = martensite fraction, never supervised, scored against COMSOL's "
             "volume average. Generated by `valvebench/evaluation/generate_comsol_leaderboard.py`.", "",
             "| model | ID RMSE (mm) | ID MAE (mm) | OOD RMSE (mm) | OOD MAE (mm) | ID ξ RMSE | OOD ξ RMSE |",
             "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for name, r in rows.items():
        lines.append(f"| {name} | " + " | ".join(ms(r[:, i]) for i in range(6)) + " |")
    return "\n".join(lines) + "\n"


def generate_comsol_leaderboard(output_path=None, seeds=SEEDS, epochs=None):
    rows, sizes = run(seeds, epochs)
    out = Path(output_path or Path(__file__).resolve().parents[2] / "comsol_leaderboard.md")
    out.write_text(render(rows, sizes, seeds), encoding="utf-8")
    return out


if __name__ == "__main__":
    print(generate_comsol_leaderboard())
